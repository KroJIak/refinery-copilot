/** Converts transport failures to plain Russian text. Machine codes remain in dev logs. */
export function userMessage(error: unknown, fallback: string): string {
  if (error instanceof ApiError) return byCode[error.code] ?? byStatus[error.status] ?? fallback;
  if (error instanceof DOMException && error.name === 'AbortError') return 'Запрос был отменён.';
  return fallback;
}

export function runFailureMessage(code: string, fallback = 'Прогон завершился с ошибкой. Повторите попытку.'): string {
  return byCode[code] ?? fallback;
}
